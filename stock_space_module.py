"""Atividades de abertura de espaço e devolução ao porta-paletes.

Registra TEMPO e QUANTIDADE física de trabalho, sem modificar alocações do WMS.
O servidor é fonte única de tempo, identidade, autorização e estado da tarefa.
"""
from __future__ import annotations

import re
from datetime import datetime
from typing import Any, Literal

from fastapi import APIRouter, FastAPI, HTTPException, Query, Request
from psycopg.errors import UniqueViolation

from supabase_module import pg_connect

router = APIRouter(prefix="/api/space-activities", tags=["Organização do estoque"])

KIND_LABELS = {
    "AJUSTE_ESTOQUE": "Abertura de espaço / ajuste físico",
    "DEVOLUCAO_PORTA_PALETES": "Devolução ao porta-paletes",
}
UNITS = {"CAIXAS", "VOLUMES", "PALETES", "PECAS"}
OPERATOR_ROLES = {
    "recebimento", "qualidade", "processamento", "etiquetagem", "estocagem",
    "devolucoes", "expedicao", "supervisor", "admin",
}
MANAGER_ROLES = {"supervisor", "admin"}
STATES = {"EM_ANDAMENTO", "PAUSADA", "CONCLUIDA"}

SCHEMA = """
CREATE TABLE IF NOT EXISTS distrilog.stock_space_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('AJUSTE_ESTOQUE','DEVOLUCAO_PORTA_PALETES')),
    street TEXT NOT NULL CHECK (length(btrim(street)) BETWEEN 1 AND 80),
    brand TEXT NOT NULL CHECK (length(btrim(brand)) BETWEEN 1 AND 100),
    operator_user_id BIGINT NOT NULL REFERENCES distrilog.users(id),
    status TEXT NOT NULL DEFAULT 'EM_ANDAMENTO'
        CHECK (status IN ('EM_ANDAMENTO','PAUSADA','CONCLUIDA')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resumed_at TIMESTAMPTZ,
    paused_at TIMESTAMPTZ,
    worked_seconds INTEGER NOT NULL DEFAULT 0 CHECK (worked_seconds >= 0),
    moved_quantity INTEGER,
    quantity_unit TEXT CHECK (quantity_unit IN ('CAIXAS','VOLUMES','PALETES','PECAS')),
    notes TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 800),
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT stock_space_completion_check CHECK (
        (status <> 'CONCLUIDA' AND moved_quantity IS NULL AND
            quantity_unit IS NULL AND finished_at IS NULL)
        OR
        (status = 'CONCLUIDA' AND moved_quantity BETWEEN 1 AND 1000000 AND
            quantity_unit IS NOT NULL AND finished_at IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS stock_space_single_active_per_operator
    ON distrilog.stock_space_activities(operator_user_id)
    WHERE status IN ('EM_ANDAMENTO','PAUSADA');
CREATE INDEX IF NOT EXISTS stock_space_recent_idx
    ON distrilog.stock_space_activities(started_at DESC, id DESC);
CREATE TABLE IF NOT EXISTS distrilog.stock_space_activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_id BIGINT NOT NULL REFERENCES distrilog.stock_space_activities(id) ON DELETE RESTRICT,
    event TEXT NOT NULL CHECK (event IN ('INICIO','PAUSA','RETOMADA','CONCLUSAO')),
    operator_user_id BIGINT NOT NULL REFERENCES distrilog.users(id),
    happened_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stock_space_events_idx
    ON distrilog.stock_space_activity_events(activity_id, happened_at);
ALTER TABLE distrilog.stock_space_activities ENABLE ROW LEVEL SECURITY;
ALTER TABLE distrilog.stock_space_activity_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON distrilog.stock_space_activities FROM PUBLIC;
REVOKE ALL ON distrilog.stock_space_activity_events FROM PUBLIC;
REVOKE ALL ON SEQUENCE distrilog.stock_space_activities_id_seq FROM PUBLIC;
REVOKE ALL ON SEQUENCE distrilog.stock_space_activity_events_id_seq FROM PUBLIC;
"""

def init_stock_space_db() -> None:
    """Idempotente; executado pelo Render no startup, sem SQLite nem dados locais."""
    with pg_connect() as con:
        with con.cursor() as cur:
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    cur.execute(statement)
            # Vanilla Postgres CI has no anon/authenticated roles; Supabase does.
            # Revoke direct role grants too, when those roles are present.
            cur.execute("SELECT rolname FROM pg_roles WHERE rolname IN ('anon','authenticated')")
            for grant_role in (r["rolname"] for r in cur.fetchall()):
                for object_name in ("stock_space_activities", "stock_space_activity_events"):
                    cur.execute(f"REVOKE ALL ON distrilog.{object_name} FROM {grant_role}")
                    cur.execute(f"REVOKE ALL ON SEQUENCE distrilog.{object_name}_id_seq FROM {grant_role}")


def _actor(request: Request, write: bool = True) -> tuple[int, str]:
    uid = getattr(request.state, "auth_user_id", None)
    role = str(getattr(request.state, "auth_role", "") or "")
    if not isinstance(uid, int) or uid <= 0:
        raise HTTPException(401, "Entre no DISTRILOG para continuar.")
    if write and role not in OPERATOR_ROLES:
        raise HTTPException(403, "Seu perfil não pode registrar movimentações de organização.")
    return uid, role


def _text(value: Any, label: str, maximum: int) -> str:
    if not isinstance(value, str):
        raise HTTPException(422, f"Informe {label}.")
    trimmed = re.sub(r"\s+", " ", value).strip()
    if not 1 <= len(trimmed) <= maximum or any(ord(ch) < 32 for ch in trimmed):
        raise HTTPException(422, f"{label} deve ter entre 1 e {maximum} caracteres.")
    return trimmed


def _start_fields(payload: Any) -> tuple[str, str, str]:
    if not isinstance(payload, dict):
        raise HTTPException(422, "Informe o tipo, a rua e a marca.")
    kind = payload.get("kind")
    if kind not in KIND_LABELS:
        raise HTTPException(422, "Selecione abertura de espaço ou devolução ao porta-paletes.")
    return kind, _text(payload.get("street"), "a rua", 80), _text(payload.get("brand"), "a marca", 100)


def _finish_fields(payload: Any) -> tuple[int, str, str]:
    if not isinstance(payload, dict):
        raise HTTPException(422, "Informe a quantidade movimentada.")
    quantity = payload.get("moved_quantity")
    if type(quantity) is not int or not 1 <= quantity <= 1_000_000:
        raise HTTPException(422, "Informe a quantidade movimentada (inteiro maior que zero).")
    unit = payload.get("quantity_unit")
    if unit not in UNITS:
        raise HTTPException(422, "Selecione caixas, volumes, paletes ou peças.")
    notes = str(payload.get("notes") or "").strip()
    if len(notes) > 800 or any(ord(ch) < 32 and ch not in "\n\t" for ch in notes):
        raise HTTPException(422, "Observações inválidas ou maiores que 800 caracteres.")
    return quantity, unit, notes


def _snapshot(row: dict[str, Any]) -> dict[str, Any]:
    """Elapsed server-side; the UI only extrapolates the seconds between refreshes."""
    seconds = int(row["worked_seconds"] or 0)
    if row["status"] == "EM_ANDAMENTO" and row["resumed_at"]:
        resumed = row["resumed_at"]
        now = datetime.now(resumed.tzinfo)
        seconds += max(0, int((now - resumed).total_seconds()))
    result = dict(row)
    result["worked_seconds_live"] = seconds
    result["kind_label"] = KIND_LABELS.get(row["kind"], row["kind"])
    return result


def _event(cur, activity_id: int, uid: int, name: str) -> None:
    cur.execute("""
        INSERT INTO distrilog.stock_space_activity_events(activity_id,operator_user_id,event)
        VALUES (%s,%s,%s)
    """, (activity_id, uid, name))


@router.get("/active")
def active_activity(request: Request) -> dict:
    uid, _ = _actor(request, write=False)
    with pg_connect() as con:
        with con.cursor() as cur:
            cur.execute("""
                SELECT a.*,u.name operator_name FROM distrilog.stock_space_activities a
                JOIN distrilog.users u ON u.id=a.operator_user_id
                WHERE a.operator_user_id=%s AND a.status IN ('EM_ANDAMENTO','PAUSADA')
                ORDER BY a.id DESC LIMIT 1
            """, (uid,))
            row = cur.fetchone()
    return {"activity": _snapshot(row) if row else None}


@router.get("")
def activity_history(
    request: Request,
    limit: int = Query(default=30, ge=1, le=100),
    scope: Literal["mine", "team"] = "mine",
) -> dict:
    uid, role = _actor(request, write=False)
    if scope == "team" and role not in MANAGER_ROLES:
        raise HTTPException(403, "Somente a supervisão pode consultar toda a equipe.")
    with pg_connect() as con:
        with con.cursor() as cur:
            sql = """
                SELECT a.*,u.name operator_name FROM distrilog.stock_space_activities a
                JOIN distrilog.users u ON u.id=a.operator_user_id
            """
            params: list[Any] = []
            if scope != "team":
                sql += " WHERE a.operator_user_id=%s"
                params.append(uid)
            sql += " ORDER BY a.started_at DESC,a.id DESC LIMIT %s"
            params.append(limit)
            cur.execute(sql, params)
            rows = cur.fetchall()
    return {"activities": [_snapshot(row) for row in rows]}


@router.post("", status_code=201)
def start_activity(request: Request, payload: dict) -> dict:
    uid, _ = _actor(request)
    kind, street, brand = _start_fields(payload)
    try:
        with pg_connect() as con:
            with con.cursor() as cur:
                cur.execute("""
                    SELECT id FROM distrilog.stock_space_activities
                    WHERE operator_user_id=%s AND status IN ('EM_ANDAMENTO','PAUSADA')
                    LIMIT 1
                """, (uid,))
                if cur.fetchone():
                    raise HTTPException(409, "Você já possui uma atividade em andamento. Conclua-a antes de iniciar outra.")
                cur.execute("""
                    INSERT INTO distrilog.stock_space_activities
                        (kind,street,brand,operator_user_id,resumed_at)
                    VALUES (%s,%s,%s,%s,now()) RETURNING *
                """, (kind, street, brand, uid))
                row = cur.fetchone()
                _event(cur, row["id"], uid, "INICIO")
                return {"ok": True, "activity": _snapshot(row)}
    except UniqueViolation as exc:
        raise HTTPException(409, "Você já possui uma atividade ativa. Atualize a tela.") from exc


def _owned_activity(cur, activity_id: int, uid: int) -> dict:
    if activity_id < 1:
        raise HTTPException(422, "Atividade inválida.")
    cur.execute("""
        SELECT a.* FROM distrilog.stock_space_activities a
        WHERE a.id=%s FOR UPDATE
    """, (activity_id,))
    row = cur.fetchone()
    if not row:
        raise HTTPException(404, "Atividade não encontrada.")
    if int(row["operator_user_id"]) != uid:
        raise HTTPException(403, "Somente o operador responsável pode controlar este cronômetro.")
    return row


@router.post("/{activity_id}/pause")
def pause_activity(activity_id: int, request: Request) -> dict:
    uid, _ = _actor(request)
    with pg_connect() as con:
        with con.cursor() as cur:
            row = _owned_activity(cur, activity_id, uid)
            if row["status"] == "PAUSADA":
                return {"ok": True, "activity": _snapshot(row), "unchanged": True}
            if row["status"] != "EM_ANDAMENTO":
                raise HTTPException(409, "Esta atividade já foi concluída.")
            cur.execute("""
                UPDATE distrilog.stock_space_activities SET
                    worked_seconds=worked_seconds+
                        GREATEST(0,FLOOR(EXTRACT(EPOCH FROM (now()-resumed_at)))::INTEGER),
                    resumed_at=NULL, paused_at=now(), status='PAUSADA', updated_at=now()
                WHERE id=%s RETURNING *
            """, (activity_id,))
            changed = cur.fetchone()
            _event(cur, activity_id, uid, "PAUSA")
    return {"ok": True, "activity": _snapshot(changed)}


@router.post("/{activity_id}/resume")
def resume_activity(activity_id: int, request: Request) -> dict:
    uid, _ = _actor(request)
    with pg_connect() as con:
        with con.cursor() as cur:
            row = _owned_activity(cur, activity_id, uid)
            if row["status"] == "EM_ANDAMENTO":
                return {"ok": True, "activity": _snapshot(row), "unchanged": True}
            if row["status"] != "PAUSADA":
                raise HTTPException(409, "Esta atividade já foi concluída.")
            cur.execute("""
                UPDATE distrilog.stock_space_activities SET
                    resumed_at=now(), paused_at=NULL, status='EM_ANDAMENTO', updated_at=now()
                WHERE id=%s RETURNING *
            """, (activity_id,))
            changed = cur.fetchone()
            _event(cur, activity_id, uid, "RETOMADA")
    return {"ok": True, "activity": _snapshot(changed)}


@router.post("/{activity_id}/finish")
def finish_activity(activity_id: int, request: Request, payload: dict) -> dict:
    uid, _ = _actor(request)
    qty, unit, notes = _finish_fields(payload)
    with pg_connect() as con:
        with con.cursor() as cur:
            row = _owned_activity(cur, activity_id, uid)
            if row["status"] == "CONCLUIDA":
                if (row["moved_quantity"] == qty and row["quantity_unit"] == unit
                        and row["notes"] == notes):
                    return {"ok": True, "activity": _snapshot(row), "unchanged": True}
                raise HTTPException(409, "A atividade já foi concluída. Abra o histórico antes de registrar outra.")
            if row["status"] not in {"PAUSADA", "EM_ANDAMENTO"}:
                raise HTTPException(409, "Estado da atividade inválido.")
            cur.execute("""
                UPDATE distrilog.stock_space_activities SET
                    worked_seconds=worked_seconds+
                        CASE WHEN status='EM_ANDAMENTO'
                             THEN GREATEST(0,FLOOR(EXTRACT(EPOCH FROM (now()-resumed_at)))::INTEGER)
                             ELSE 0 END,
                    resumed_at=NULL, paused_at=NULL,
                    status='CONCLUIDA',
                    moved_quantity=%s, quantity_unit=%s, notes=%s,
                    finished_at=now(), updated_at=now()
                WHERE id=%s RETURNING *
            """, (qty, unit, notes, activity_id))
            changed = cur.fetchone()
            _event(cur, activity_id, uid, "CONCLUSAO")
    return {"ok": True, "activity": _snapshot(changed)}


def register_stock_space_routes(app: FastAPI) -> None:
    app.include_router(router)
